"""Private workspace storage boundary for the investigation application."""

from contextlib import AbstractContextManager
from typing import Protocol

from vulnwitness.domain.session_record import SessionCheckReport, SessionFindings, SessionRecord
from vulnwitness.domain.session_report import CheckedSession
from vulnwitness.domain.workspace import InvestigationId, RequestKey, RequestRecord


class WorkspaceFiles(Protocol):
    def workspace_lock(self) -> AbstractContextManager[None]: ...
    def investigation_lock(self, session_id: InvestigationId) -> AbstractContextManager[None]: ...
    def is_busy(self, session_id: InvestigationId) -> bool: ...
    def list_ids(self) -> tuple[str, ...]: ...
    def read_request(self, key: RequestKey) -> RequestRecord | None: ...
    def write_request(self, key: RequestKey, record: RequestRecord) -> None: ...
    def create(self, session: SessionRecord) -> None: ...
    def read_response(self, session_id: InvestigationId, sequence: int) -> bytes: ...
    def read(self, session_id: InvestigationId, name: str) -> bytes: ...
    def write_findings(self, session_id: InvestigationId, findings: SessionFindings) -> None: ...
    def write(self, session_id: InvestigationId, name: str, content: bytes) -> None: ...
    def exists(self, session_id: InvestigationId, name: str) -> bool: ...
    def input_digest(self, session_id: InvestigationId) -> str: ...
    def check_findings(
        self, session_id: InvestigationId, findings: SessionFindings
    ) -> SessionCheckReport: ...
    def check(self, session_id: InvestigationId) -> CheckedSession: ...
    def local_path(self, session_id: InvestigationId, name: str) -> str: ...
    def is_orphan(self, session_id: InvestigationId) -> bool: ...
